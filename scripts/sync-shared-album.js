#!/usr/bin/env node

/*
  Sync a public iCloud Shared Album or a public Google Photos shared link into
  config/photos.json.

  Usage:
    node scripts/sync-shared-album.js

  Reads config/album-source.json. If `enabled` is false, exits successfully
  without changes. Detects provider when `provider` is "auto".

  iCloud Shared Albums use Apple's public sharedstreams JSON API (the same one
  that the iCloud web viewer uses). The token is the part after the `#` in the
  share URL, e.g. https://www.icloud.com/sharedalbum/#B0xxxxxxxxx → B0xxxxxxxxx.

  Google Photos shared albums are best-effort scraping of the public HTML page.
  Google does not provide a stable public CDN/API for shared albums, so this
  may break without warning. Prefer iCloud for reliability.
*/

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const CONFIG_PATH = path.join(ROOT, "config", "album-source.json");

async function main() {
  const config = readJson(CONFIG_PATH);

  if (!config.enabled) {
    console.log("Album sync is disabled (config/album-source.json: enabled=false). Nothing to do.");
    return;
  }

  const url = (config.url || "").trim();
  if (!url) {
    fail("config/album-source.json: 'url' is empty. Paste a shared-album link.");
  }

  const provider = detectProvider(config.provider, url);
  const videoMinDurationMs = resolveVideoMinDurationMs(config.videoMinDurationMs);
  console.log(`Syncing shared album using provider: ${provider}`);
  console.log(`Source URL: ${url}`);
  console.log(`Video minimum duration: ${videoMinDurationMs}ms (items shorter than this are imported as still images).`);

  let photos;
  if (provider === "icloud") {
    photos = await syncICloud(url, { videoMinDurationMs });
  } else if (provider === "google") {
    photos = await syncGooglePhotos(url, { videoMinDurationMs });
  } else {
    fail(`Unknown provider: ${provider}. Use "icloud", "google", or "auto".`);
  }

  if (!photos || !photos.length) {
    fail("No media items were discovered in the shared album.");
  }

  if (config.saveToRepo) {
    console.log("Repo storage enabled — photos will be committed alongside photos.json.");
    photos = await savePhotosToRepo(photos);
  } else if (config.driveFolderId && process.env.GDRIVE_OAUTH_CLIENT && process.env.GDRIVE_TOKEN) {
    console.log(`Google Drive sync enabled — folder: ${config.driveFolderId}`);
    photos = await syncWithDrive(photos, config.driveFolderId);
  }

  const outputRel = config.output || "config/photos.json";
  const outputPath = path.join(ROOT, outputRel);

  const manifest = {
    source: {
      mode: "synced",
      provider,
      syncedAt: new Date().toISOString(),
      notes:
        "Generated by scripts/sync-shared-album.js. Edit config/album-source.json to change the source. Manual edits will be overwritten on the next sync."
    },
    photos
  };

  fs.writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`Wrote ${outputRel} with ${photos.length} media item(s).`);
}

// Default minimum duration before an item is treated as a real video. Apple/
// Google's "Live Photo" / "motion photo" feature attaches a 1.5–3s clip to a
// still image; those clips are flagged in shared-album metadata the same way
// real videos are, but exporting them as `"type": "video"` produces broken
// playback (the =dv URL often returns just the still frame, or a janky 2s
// clip). Real captured videos are typically much longer, so requiring
// duration >= 20s is a pragmatic cutoff that filters Live Photos out without
// dropping intentional clips. Override per-album by setting
// `videoMinDurationMs` in `config/album-source.json`.
const DEFAULT_VIDEO_MIN_DURATION_MS = 20000;

function resolveVideoMinDurationMs(value) {
  if (value === undefined || value === null) return DEFAULT_VIDEO_MIN_DURATION_MS;
  const n = Number(value);
  if (!Number.isFinite(n) || n < 0) {
    console.warn(
      `config/album-source.json: ignoring invalid videoMinDurationMs=${JSON.stringify(value)}; falling back to ${DEFAULT_VIDEO_MIN_DURATION_MS}ms.`
    );
    return DEFAULT_VIDEO_MIN_DURATION_MS;
  }
  return Math.round(n);
}

function detectProvider(provider, url) {
  const normalized = (provider || "auto").toLowerCase();
  if (normalized === "icloud" || normalized === "google") return normalized;
  if (/icloud\.com\/sharedalbum/i.test(url)) return "icloud";
  if (/photos\.app\.goo\.gl|photos\.google\.com\/share/i.test(url)) return "google";
  fail(
    `Could not auto-detect provider from URL. Set "provider" to "icloud" or "google" in config/album-source.json.`
  );
}

/* ---------- iCloud ---------- */

function extractICloudToken(url) {
  const hash = url.split("#")[1];
  if (hash) return hash.split(/[?&/]/)[0];
  const tail = url.replace(/\/$/, "").split("/").pop();
  if (tail && /^[A-Za-z0-9]+$/.test(tail)) return tail;
  fail(`Could not extract iCloud share token from URL: ${url}`);
}

function icloudPartition(token) {
  const first = token.charAt(0).toUpperCase();
  if (first === "A") return "01";
  const map = { B: "02", C: "03", D: "04", E: "05", F: "06", G: "07", H: "08", I: "09", J: "10" };
  return map[first] || "01";
}

async function icloudPost(host, token, endpoint, body) {
  const url = `https://${host}/${token}/sharedstreams/${endpoint}`;
  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json",
      Origin: "https://www.icloud.com",
      Referer: "https://www.icloud.com/"
    },
    body: JSON.stringify(body)
  });

  const redirectHost = response.headers.get("x-apple-mme-host");
  return { response, redirectHost };
}

async function syncICloud(url, options = {}) {
  const videoMinDurationMs = options.videoMinDurationMs || DEFAULT_VIDEO_MIN_DURATION_MS;
  const token = extractICloudToken(url);
  let host = `p${icloudPartition(token)}-sharedstreams.icloud.com`;

  let result = await icloudPost(host, token, "webstream", { streamCtag: null });
  if (result.redirectHost) {
    host = result.redirectHost;
    result = await icloudPost(host, token, "webstream", { streamCtag: null });
  }
  if (!result.response.ok) {
    fail(`iCloud webstream request failed: HTTP ${result.response.status}. Album may be private or the link expired.`);
  }
  const stream = await result.response.json();
  const photoGuids = (stream.photos || []).map((p) => p.photoGuid).filter(Boolean);
  if (!photoGuids.length) {
    fail("iCloud album returned no photos. Check that the album is public and shared.");
  }

  const assetResult = await icloudPost(host, token, "webasseturls", { photoGuids });
  if (!assetResult.response.ok) {
    fail(`iCloud webasseturls request failed: HTTP ${assetResult.response.status}.`);
  }
  const assets = await assetResult.response.json();
  const items = assets.items || {};
  const locations = assets.locations || {};

  function buildItemUrl(checksum) {
    const item = items[checksum];
    if (!item) return null;
    const location = locations[item.url_location];
    if (!location || !location.hosts || !location.hosts.length) return null;
    return `${location.scheme || "https"}://${location.hosts[0]}${item.url_path}`;
  }

  const photos = [];
  let livePhotoCount = 0;
  let index = 0;
  for (const photo of stream.photos || []) {
    index += 1;
    const markerSaysVideo =
      Boolean(photo.mediaAssetType && /video/i.test(photo.mediaAssetType)) ||
      hasVideoDerivative(photo.derivatives);
    const durationMs = extractICloudDurationMs(photo);
    const longEnough =
      typeof durationMs === "number" && durationMs >= videoMinDurationMs;
    // Apple Live Photos report a video derivative AND a short duration. Emit
    // "video" when the marker agrees AND either duration confirms it OR duration
    // is unknown (iCloud shared-album videos are reliably real; Live Photos
    // virtually always have a detectable short duration).
    const isVideo = markerSaysVideo && (longEnough || durationMs === null);
    if (markerSaysVideo && !isVideo) {
      livePhotoCount += 1;
      console.log(
        `iCloud: item ${index} flagged as video but duration=${durationMs ?? "unknown"}ms < ${videoMinDurationMs}ms — exporting as still image (likely Live Photo).`
      );
    }
    let chosen = pickBestDerivative(photo.derivatives, isVideo);
    let emitAsVideo = isVideo;
    if (!chosen && isVideo) {
      // No video-typed derivative found even though the item is marked as a video.
      // Log derivative structure to help diagnose what keys/mimeTypes iCloud returned.
      if (photo.derivatives) {
        const derivInfo = Object.entries(photo.derivatives)
          .map(([k, v]) => `"${k}"→mediaType:${(v && v.mediaType) || "none"}`)
          .join(", ");
        console.log(`iCloud: item ${index} derivatives: [${derivInfo}]`);
      } else {
        console.log(`iCloud: item ${index} has no derivatives object`);
      }
      console.log(
        `iCloud: item ${index} marked as video but no video stream derivative found — importing as still image.`
      );
      // Fall back to best image derivative; downgrade to "image" so we don't
      // save an image URL as type "video" (broken playback).
      chosen = pickBestDerivative(photo.derivatives, false);
      emitAsVideo = false;
    }
    if (!chosen || !chosen.checksum) continue;
    const mediaUrl = buildItemUrl(chosen.checksum);
    if (!mediaUrl) continue;
    photos.push({
      url: mediaUrl,
      alt: `Erinnerung ${index}`,
      type: emitAsVideo ? "video" : "image",
      guid: photo.photoGuid || null
    });
  }

  if (!photos.length) {
    fail("iCloud album was readable but no resolvable media URLs were produced.");
  }
  if (livePhotoCount) {
    console.log(
      `iCloud: ${livePhotoCount} short-clip item(s) downgraded to still image (threshold: duration>=${videoMinDurationMs}ms).`
    );
  }
  return photos;
}

function extractICloudDurationMs(photo) {
  if (!photo) return null;
  const candidates = [
    photo.mediaAssetDurationInMilliseconds,
    photo.mediaAssetDurationMs,
    photo.durationMs,
    typeof photo.mediaAssetDuration === "number" ? photo.mediaAssetDuration * 1000 : null,
    typeof photo.duration === "number" ? photo.duration * 1000 : null
  ];
  for (const v of candidates) {
    if (typeof v === "number" && Number.isFinite(v) && v > 0) return v;
    if (typeof v === "string" && v.trim() && Number.isFinite(Number(v))) return Number(v);
  }
  if (photo.derivatives) {
    for (const key of Object.keys(photo.derivatives)) {
      const d = photo.derivatives[key];
      if (!d) continue;
      const dur = d.duration ?? d.durationInMilliseconds ?? d.durationMs;
      if (typeof dur === "number" && Number.isFinite(dur) && dur > 0) {
        return dur > 1000 ? dur : dur * 1000;
      }
    }
  }
  return null;
}

function isVideoEntry(key, d) {
  if (d && typeof d.mediaType === "string" && /video|mp4|quicktime/i.test(d.mediaType)) return true;
  if (/video|mp4|quicktime|movie/i.test(key || "")) return true;
  return false;
}

function hasVideoDerivative(derivatives) {
  if (!derivatives) return false;
  for (const [key, d] of Object.entries(derivatives)) {
    if (isVideoEntry(key, d)) return true;
  }
  return false;
}

function pickBestDerivative(derivatives, preferVideo) {
  if (!derivatives) return null;
  // Use _k to avoid clobbering a 'key' property that may exist in the derivative value
  const entries = Object.entries(derivatives).map(([k, value]) => ({ ...value, _k: k }));
  if (!entries.length) return null;
  if (preferVideo) {
    const videos = entries.filter((d) => isVideoEntry(d._k, d));
    if (videos.length) {
      videos.sort((a, b) => sizeOf(b) - sizeOf(a));
      return videos[0];
    }
    return null;
  }
  entries.sort((a, b) => sizeOf(b) - sizeOf(a));
  return entries[0];
}

function sizeOf(d) {
  const w = parseInt(d.width, 10) || 0;
  const h = parseInt(d.height, 10) || 0;
  return w * h || parseInt(d.fileSize, 10) || 0;
}

/* ---------- Google Photos (best-effort) ---------- */

async function syncGooglePhotos(url, options = {}) {
  const videoMinDurationMs = options.videoMinDurationMs || DEFAULT_VIDEO_MIN_DURATION_MS;
  console.warn(
    "Google Photos sync is best-effort scraping. Google does not provide a stable public API for shared albums; this may break."
  );
  let response;
  try {
    response = await fetch(url, {
      headers: {
        "User-Agent":
          "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36",
        Accept: "text/html,application/xhtml+xml"
      },
      redirect: "follow"
    });
  } catch (error) {
    fail(`Google Photos fetch failed: ${error.message}`);
  }
  if (!response.ok) {
    fail(`Google Photos request failed: HTTP ${response.status}. The album may not be public.`);
  }
  const html = await response.text();

  // Public Google Photos shared albums embed an AF_initDataCallback for ds:1
  // that contains the ordered list of media items with their media-type marker
  // and optional duration. Parsing this gives us reliable image vs. video
  // detection and preserves album order. URL-pattern fallback is used only if
  // the structured payload is missing or unparseable.
  const items = parseGooglePhotosItems(html, videoMinDurationMs);
  if (items && items.length) {
    const photos = await buildGooglePhotosFromItems(items);
    if (photos.length) {
      const imageCount = photos.filter((p) => p.type === "image").length;
      const videoCount = photos.filter((p) => p.type === "video").length;
      console.log(
        `Google Photos: parsed ${photos.length} item(s) — ${imageCount} image(s), ${videoCount} video(s).`
      );
      if (videoCount === 0) {
        console.warn(
          "Google Photos: no playable video URLs were resolved. If the album contains videos, the share page may not expose them as MP4 — consider an iCloud public shared album for reliable video URLs."
        );
      }
      return photos;
    }
  }

  console.warn(
    "Google Photos: structured data parse failed, falling back to URL pattern scrape (videos cannot be detected this way)."
  );
  const urlPattern = /https:\/\/lh\d\.googleusercontent\.com\/[\w\-./=?]+/g;
  const found = html.match(urlPattern) || [];
  const seen = new Set();
  const photos = [];
  let index = 0;
  for (const raw of found) {
    const cleaned = raw.replace(/=[swh][\d-]+(?:[-\w]+)?$/, "");
    const finalUrl = `${cleaned}=s2048`;
    if (seen.has(finalUrl)) continue;
    seen.add(finalUrl);
    index += 1;
    photos.push({
      url: finalUrl,
      alt: `Erinnerung ${index}`,
      type: "image"
    });
  }

  if (!photos.length) {
    fail(
      "Google Photos scraping found no media. The page format may have changed, or the album is not public. " +
        "Consider switching to a public iCloud Shared Album for reliability."
    );
  }
  console.warn(
    `Google Photos fallback: scraped ${photos.length} image(s). Videos are not reliably detectable via fallback and are skipped.`
  );
  return photos;
}

// Live Photos / motion photos appear in the ds:1 payload looking very similar
// to real videos: they carry a non-image media-type marker and a short
// duration. Treating them as videos produces broken playback (the =dv URL
// either redirects to the still frame or to a short clip that renders
// poorly). We only trust an item as a real video when both:
//   1) the structured marker reads as video (14 — other non-1 markers tend
//      to be motion/live photos), AND
//   2) duration is at least the configured `videoMinDurationMs`
//      (default DEFAULT_VIDEO_MIN_DURATION_MS = 20s). Real captured videos
//      are typically much longer; Live Photos are ~1.5–3s clips bundled
//      with a still.
// Anything ambiguous is downgraded to image so the still frame renders
// correctly instead of a janky short clip.
const VIDEO_TYPE_MARKER = 14;

function parseGooglePhotosItems(html, videoMinDurationMs = DEFAULT_VIDEO_MIN_DURATION_MS) {
  // The ds:1 init-data block contains an array of media items. Each item is
  // shaped roughly:
  //   [ id, [url, w, h, ..., [null, null, mediaTypeMarker], [fileSize], ...], timestamp, ..., { "146008172": [null, durationMs] } ]
  // mediaTypeMarker: 1 = image, 14 = video. Other markers (e.g. motion/live)
  // are present on Live Photos and short motion frames — those are NOT
  // playable videos and should be exported as still images.
  const start = html.indexOf("AF_initDataCallback({key: 'ds:1'");
  if (start < 0) return null;
  const dataIdx = html.indexOf("data:", start);
  if (dataIdx < 0) return null;
  const tail = html.slice(dataIdx + 5);
  const sideIdx = tail.indexOf(", sideChannel");
  if (sideIdx < 0) return null;
  const jsonText = tail.slice(0, sideIdx);
  let parsed;
  try {
    parsed = JSON.parse(jsonText);
  } catch (_error) {
    return null;
  }
  const items = Array.isArray(parsed) ? parsed[1] : null;
  if (!Array.isArray(items)) return null;
  const out = [];
  for (const entry of items) {
    if (!Array.isArray(entry)) continue;
    const meta = entry[1];
    if (!Array.isArray(meta) || typeof meta[0] !== "string") continue;
    const baseUrl = meta[0];
    if (!/^https:\/\/lh\d\.googleusercontent\.com\//.test(baseUrl)) continue;
    let typeMarker = null;
    for (let i = 2; i < meta.length; i += 1) {
      const v = meta[i];
      if (Array.isArray(v) && v.length === 3 && typeof v[2] === "number") {
        typeMarker = v[2];
        break;
      }
    }
    let durationMs = null;
    const extras = entry[entry.length - 1];
    if (extras && typeof extras === "object" && !Array.isArray(extras)) {
      const dur = extras["146008172"];
      if (Array.isArray(dur) && typeof dur[1] === "number") durationMs = dur[1];
    }
    const markerSaysVideo = typeMarker === VIDEO_TYPE_MARKER;
    const longEnough = typeof durationMs === "number" && durationMs >= videoMinDurationMs;
    // When duration is unknown (null) and the marker says video, optimistically
    // mark as video so canFetchAsVideo can verify the =dv URL is streamable.
    // This handles cases where the structured-data duration key has changed or
    // the duration field is absent — the =dv probe is the authoritative check.
    const isVideo = markerSaysVideo && (longEnough || durationMs === null);
    const isLivePhoto =
      typeMarker !== null && typeMarker !== 1 && !isVideo;
    out.push({
      baseUrl,
      isVideo,
      isLivePhoto,
      typeMarker,
      durationMs,
      videoMinDurationMs
    });
  }
  return out;
}

async function buildGooglePhotosFromItems(items) {
  const photos = [];
  let livePhotoCount = 0;
  let skippedVideoCount = 0;
  let downgradedShortCount = 0;
  let unknownDurationFallbackCount = 0;
  const threshold =
    items[0] && items[0].videoMinDurationMs ? items[0].videoMinDurationMs : DEFAULT_VIDEO_MIN_DURATION_MS;
  let index = 0;
  for (const item of items) {
    index += 1;
    const cleaned = item.baseUrl.replace(/=[swhmd][\w\d-]*$/, "");
    if (item.isVideo) {
      const videoUrl = `${cleaned}=dv`;
      const ok = await canFetchAsVideo(videoUrl);
      if (ok) {
        photos.push({
          url: videoUrl,
          alt: `Erinnerung ${index}`,
          type: "video"
        });
        continue;
      }
      if (item.durationMs === null) {
        // Duration unknown — =dv did not verify, so we cannot confirm this is a
        // real video (it might be a Live Photo or motion frame). Fall back to the
        // still image rather than dropping the item entirely.
        unknownDurationFallbackCount += 1;
        console.log(
          `Google Photos: item ${index} has video marker but unknown duration and =dv did not resolve — importing as still image.`
        );
        photos.push({
          url: `${cleaned}=s2048`,
          alt: `Erinnerung ${index}`,
          type: "image"
        });
        continue;
      }
      skippedVideoCount += 1;
      console.warn(
        `Google Photos: item ${index} looked like a video (marker=${item.typeMarker}, duration=${item.durationMs}ms) but no playable URL could be resolved — skipping. Use iCloud sharing for reliable video URLs.`
      );
      continue;
    }
    if (item.typeMarker === VIDEO_TYPE_MARKER) {
      // Marker said video but duration was below threshold: it was downgraded
      // to image. Track separately from Live Photos so the user knows whether
      // they need to bump videoMinDurationMs.
      downgradedShortCount += 1;
      console.log(
        `Google Photos: item ${index} marked as video but duration=${item.durationMs ?? "unknown"}ms < ${threshold}ms — exporting still image instead. Adjust 'videoMinDurationMs' in config/album-source.json if this is a real short clip.`
      );
    } else if (item.isLivePhoto) {
      livePhotoCount += 1;
      console.log(
        `Google Photos: item ${index} is a Live Photo / motion frame (marker=${item.typeMarker}, duration=${item.durationMs}ms) — exporting still image only.`
      );
    }
    photos.push({
      url: `${cleaned}=s2048`,
      alt: `Erinnerung ${index}`,
      type: "image"
    });
  }
  if (livePhotoCount) {
    console.log(
      `Google Photos: ${livePhotoCount} Live Photo(s) emitted as still images (threshold: video marker=14 AND duration>=${threshold}ms).`
    );
  }
  if (downgradedShortCount) {
    console.warn(
      `Google Photos: ${downgradedShortCount} item(s) flagged as video were below the ${threshold}ms duration threshold and were exported as still images. Set 'videoMinDurationMs' in config/album-source.json to lower the cutoff.`
    );
  }
  if (unknownDurationFallbackCount) {
    console.log(
      `Google Photos: ${unknownDurationFallbackCount} video-marker item(s) had no readable duration and =dv did not resolve — imported as still images. If these are real videos, consider switching to an iCloud public shared album for reliable video URLs.`
    );
  }
  if (skippedVideoCount) {
    console.log(
      `Google Photos: ${skippedVideoCount} ambiguous video item(s) skipped because no playable stream URL resolved.`
    );
  }
  return photos;
}

async function canFetchAsVideo(url) {
  try {
    const res = await fetch(url, {
      method: "GET",
      redirect: "manual",
      headers: {
        "User-Agent":
          "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"
      }
    });
    if (res.status >= 300 && res.status < 400) {
      const loc = res.headers.get("location") || "";
      return /videoplayback|video-downloads|googlevideo\.com/.test(loc);
    }
    if (res.ok) {
      const ct = (res.headers.get("content-type") || "").toLowerCase();
      return ct.startsWith("video/");
    }
    return false;
  } catch (_error) {
    return false;
  }
}

/* ---------- Repo photo storage (no external auth) ---------- */

const MAX_REPO_FILE_BYTES = 50 * 1024 * 1024; // 50 MB — GitHub hard limit for individual files

async function savePhotosToRepo(photos) {
  const PHOTOS_DIR = path.join(ROOT, "media", "photos");
  fs.mkdirSync(PHOTOS_DIR, { recursive: true });

  const result = [];
  let downloaded = 0;
  let reused = 0;
  let skipped = 0;

  for (const photo of photos) {
    const ext = photo.type === "video" ? "mp4" : "jpg";
    const filename = `${photo.alt}.${ext}`;
    const filepath = path.join(PHOTOS_DIR, filename);

    if (fs.existsSync(filepath)) {
      reused++;
      result.push({ ...photo, url: `../media/photos/${filename}` });
      continue;
    }

    process.stdout.write(`Repo: downloading ${filename}... `);
    let buffer;
    try {
      const resp = await fetch(photo.url, { headers: { "User-Agent": "Mozilla/5.0" } });
      if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
      buffer = Buffer.from(await resp.arrayBuffer());
    } catch (err) {
      console.warn(`\nRepo: download failed (${err.message}), keeping iCloud URL for ${filename}.`);
      result.push(photo);
      skipped++;
      continue;
    }

    if (buffer.length > MAX_REPO_FILE_BYTES) {
      console.warn(`\nRepo: ${filename} is ${(buffer.length / 1024 / 1024).toFixed(1)} MB — over 50 MB limit, keeping iCloud URL.`);
      result.push(photo);
      skipped++;
      continue;
    }

    fs.writeFileSync(filepath, buffer);
    console.log(`done (${(buffer.length / 1024).toFixed(0)} KB)`);
    downloaded++;
    // URL resolves relative to config/photos.json base
    result.push({ ...photo, url: `../media/photos/${filename}` });
  }

  console.log(`Repo: ${downloaded} downloaded, ${reused} reused, ${skipped} kept original URL.`);
  return result;
}

/* ---------- Google Drive upload ---------- */

async function syncWithDrive(photos, folderId) {
  let google;
  try {
    ({ google } = require("googleapis"));
  } catch (_) {
    fail("googleapis package not found. Run `npm install` first.");
  }

  let clientData, tokenData;
  try {
    clientData = JSON.parse(process.env.GDRIVE_OAUTH_CLIENT);
    tokenData  = JSON.parse(process.env.GDRIVE_TOKEN);
  } catch (_) {
    fail("GDRIVE_OAUTH_CLIENT or GDRIVE_TOKEN secret is not valid JSON.");
  }
  const creds = clientData.installed || clientData.web;
  if (!creds) fail("GDRIVE_OAUTH_CLIENT does not look like a Google OAuth client JSON.");

  const auth = new google.auth.OAuth2(creds.client_id, creds.client_secret);
  auth.setCredentials(tokenData);
  const drive = google.drive({ version: "v3", auth });

  // Load manifest: maps GUID → { alt, ext, driveId }
  const MANIFEST_PATH = path.join(ROOT, "config", "drive-manifest.json");
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"));
  } catch (_) {
    manifest = { photos: {}, nextIndex: 1 };
  }
  if (!manifest.photos) manifest.photos = {};
  if (!manifest.nextIndex) manifest.nextIndex = 1;

  // List all files currently in the Drive folder (ID + name for name-based recovery)
  const driveFileIds = new Set();
  const driveNameToId = {}; // "Erinnerung 1.jpg" → fileId
  let pageToken;
  do {
    const { data } = await drive.files.list({
      q: `'${folderId}' in parents and trashed=false`,
      fields: "nextPageToken,files(id,name)",
      pageToken,
      pageSize: 1000
    });
    for (const f of data.files || []) {
      driveFileIds.add(f.id);
      if (f.name) driveNameToId[f.name] = f.id;
    }
    pageToken = data.nextPageToken;
  } while (pageToken);

  console.log(`Drive: ${driveFileIds.size} existing file(s) in folder.`);

  const { Readable } = require("stream");
  const result = [];
  let uploaded = 0;
  let reused = 0;

  for (const photo of photos) {
    // Resolve or create manifest entry
    let entry = photo.guid ? manifest.photos[photo.guid] : null;
    if (!entry) {
      const alt = `Erinnerung ${manifest.nextIndex}`;
      manifest.nextIndex += 1;
      entry = { alt, ext: null, driveId: null };
      if (photo.guid) manifest.photos[photo.guid] = entry;
    }

    let needsUpload = !entry.driveId || !driveFileIds.has(entry.driveId);

    // When manifest lacks a driveId (e.g. manifest was lost), check Drive by name
    // so we reuse existing uploads rather than duplicating them.
    if (needsUpload && entry.alt) {
      for (const tryExt of ["jpg", "mov", "mp4"]) {
        const candidate = driveNameToId[`${entry.alt}.${tryExt}`];
        if (candidate) {
          entry.driveId = candidate;
          if (!entry.ext) entry.ext = tryExt;
          needsUpload = false;
          reused++;
          console.log(`Drive: found ${entry.alt}.${tryExt} in folder by name — reusing (${candidate}).`);
          break;
        }
      }
    }

    if (needsUpload) {
      const filename = entry.alt + (entry.ext ? `.${entry.ext}` : "");
      process.stdout.write(`Drive: uploading ${entry.alt}... `);
      let buffer, contentType;
      try {
        const resp = await fetch(photo.url, { headers: { "User-Agent": "Mozilla/5.0" } });
        if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
        contentType = resp.headers.get("Content-Type") || "";
        buffer = Buffer.from(await resp.arrayBuffer());
      } catch (err) {
        console.warn(`\nDrive: download failed (${err.message}), keeping original URL for ${entry.alt}.`);
        result.push(photo);
        continue;
      }

      // Detect actual mime type from response Content-Type
      let ext, mimeType;
      if (/quicktime/i.test(contentType)) {
        ext = "mov";
        mimeType = "video/quicktime";
      } else if (photo.type === "video") {
        ext = "mp4";
        mimeType = "video/mp4";
      } else {
        ext = "jpg";
        mimeType = "image/jpeg";
      }

      entry.ext = ext;
      const uploadName = `${entry.alt}.${ext}`;

      let fileId;
      try {
        const { data: file } = await drive.files.create({
          requestBody: { name: uploadName, parents: [folderId] },
          media: { mimeType, body: Readable.from(buffer) },
          fields: "id"
        });
        fileId = file.id;
        await drive.permissions.create({
          fileId,
          requestBody: { role: "reader", type: "anyone" }
        });
        console.log(`done (${fileId})`);
        entry.driveId = fileId;
        uploaded++;
      } catch (err) {
        console.warn(`\nDrive: upload failed (${err.message}), keeping original URL for ${entry.alt}.`);
        result.push(photo);
        continue;
      }
    } else {
      reused++;
    }

    // Build stable Drive CDN URL
    const isVideo = entry.ext === "mov" || entry.ext === "mp4";
    const driveUrl = isVideo
      ? `https://drive.google.com/uc?export=download&id=${entry.driveId}&confirm=t`
      : `https://lh3.googleusercontent.com/d/${entry.driveId}`;

    result.push({ ...photo, alt: entry.alt, url: driveUrl });
  }

  // Persist updated manifest
  fs.writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);

  console.log(`Drive: ${uploaded} uploaded, ${reused} reused from previous sync.`);
  return result;
}

/* ---------- helpers ---------- */

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    fail(`Could not read ${filePath}: ${error.message}`);
  }
}

function fail(message) {
  console.error(`sync-shared-album: ${message}`);
  process.exit(1);
}

main().catch((error) => {
  console.error(`sync-shared-album: unexpected error: ${error && error.message ? error.message : error}`);
  process.exit(1);
});
